-- Фолбэк: текущий язык -> enUS -> сам ключ
local enUS = setmetatable(locales.enUS, { __index = function(_, key) return key end })
local L = locales[GetLocale()]
if L and L ~= enUS then
    setmetatable(L, { __index = enUS })
else
    L = enUS
end
ns.L = L
